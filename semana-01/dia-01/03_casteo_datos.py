# es el proceso de convertir un tipo de dato a otro tipo de dato
# el int convierte a entero
print(int("100"))

#el str convierte a cadena de texto
print(str(100))

#el float convierte a decimal
print(float("3.14"))    

print(float("3.14") + 1.0)

# el round redondea un numero decimal a un numero entero
print(round(3.14))
